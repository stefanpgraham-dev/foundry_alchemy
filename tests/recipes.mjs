import assert from 'node:assert/strict';
import fs from 'node:fs';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {seedDefaults,validateRecipe,validateLibrary,restoreDefault,importMissingDefaults,mergeRecipeLibraries,recipeDC,recipeHours,recipeTest,parseRecipeImport,exportRecipeLibrary,recipeComparison} from '../scripts/recipes.mjs';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const original=JSON.parse(readFileSync(path.join(root,'data/recipes.json'),'utf8'));
const seeded=seedDefaults(original,{'potion-of-healing':'Item.healing'});
assert.equal(seeded.length,44);
assert.equal(seeded[0].id,'potion-of-healing');
assert.equal(seeded[0].source,'default');
assert.equal(seeded[0].outputUuid,'Item.healing');
assert.equal(seeded[0].cost.common_curative,3);
assert.equal(recipeDC(seeded[0]),10);
assert.equal(recipeHours(seeded[0]),2);
// Altering a world recipe cannot modify the shipped defaults.
const edited={...seeded[0],name:'Altered Healing',cost:{rare_curative:2,common_reactive:1},dcOverride:17,hoursOverride:3.25};
const valid=validateRecipe(edited);
assert.equal(recipeDC(valid),17);
assert.equal(recipeHours(valid),3.25);
assert.equal(original[0].cost.common_curative,3);
const restored=restoreDefault(valid,original);
assert.deepEqual(restored.cost,{common_curative:3});
assert.equal(restored.outputUuid,'Item.healing');
assert.equal(restored.dcOverride,null);
assert.equal(restored.hoursOverride,null);
// Stable IDs; duplicate, disable, restore and reimport missing defaults.
const withoutOne=seeded.filter(x=>x.id!==seeded[3].id);
assert.equal(importMissingDefaults(withoutOne,original).length,44);
assert.equal(importMissingDefaults(seeded,original).length,44);
assert.throws(()=>validateLibrary([seeded[0],seeded[0]]),/Duplicate recipe ID/);
assert.throws(()=>validateRecipe({...valid,cost:{unknown:1}}),/Unknown reagent/);
assert.throws(()=>validateRecipe({...valid,cost:{rare_curative:0}}),/whole numbers/);
assert.throws(()=>validateRecipe({...valid,dcOverride:90}),/Override DC/);
assert.throws(()=>validateRecipe({...valid,hoursOverride:3.3}),/quarter-hour/);
assert.throws(()=>validateRecipe({id:'custom-example',name:'New',cost:{rare_reactive:1},source:'custom'}),/output Item/);
const custom=validateRecipe({id:'custom-example',name:'Potion of Clarity',cost:{rare_reactive:2,common_curative:1},source:'custom',outputUuid:'Item.customPotion',enabled:false});
assert.equal(custom.enabled,false);
assert.deepEqual(validateLibrary([custom]),[custom]);
const imported=parseRecipeImport(exportRecipeLibrary([custom,edited]));
assert.equal(imported.length,2);
assert.equal(imported[0].outputUuid,'Item.customPotion');
assert.equal(imported[1].cost.rare_curative,2);
assert.throws(()=>parseRecipeImport('{"schema":2,"recipes":[]}'),/compatible/);
assert.equal(mergeRecipeLibraries([seeded[0]],[edited],{overwrite:false})[0].name,'Potion of Healing');
assert.equal(mergeRecipeLibraries([seeded[0]],[edited],{overwrite:true})[0].name,'Altered Healing');
assert.equal(mergeRecipeLibraries([seeded[0]],[custom],{replace:true}).length,1);
assert.equal(recipeComparison([seeded[0]],[edited,custom]).added.length,1);
assert.equal(recipeComparison([seeded[0]],[edited,custom]).changed.length,1);
const inventory=[{id:'r',key:'rare_curative',quantity:3},{id:'c',key:'common_reactive',quantity:10}];
const test=recipeTest(valid,1,inventory);
assert(test.craftable);
assert.equal(test.plan.consume.find(x=>x.id==='r').quantity,2);
assert.equal(test.dc,17);
assert.equal(test.hours,3.25);
assert.equal(test.maximumCraftable,1);
assert.equal(recipeTest(valid,2,inventory).craftable,false);
assert.equal(inventory[0].quantity,3,'dry run never mutates inventory');
console.log('Recipe library validation, migration, overrides, import/export and dry runs passed.');
